"""INC46 T02 — Rule assets: deterministic MUST / MUST_NOT rules from the trace.

The "rules discovered while doing the work" are **extracted from real evidence**
— never generated by a language model. :func:`extract_rules` is a pure function
over (patterns, runs) that emits:

  * ``must``     — ``Y`` was executed before ``X`` in the successful runs
    (``confidence = #{Y before X} / N``);
  * ``must_not`` — tool ``T`` errored in ``≥ min_support`` runs and **never**
    succeeded (``confidence = #{errored} / #{runs that called T}``).

Every rule carries its ``support`` and ``confidence`` (both recomputable) plus
``source_run_ids`` — the evidence runs — so a reviewer can retrace it. The rule
**text** is a fixed template filled with those real numbers; there is no
generative step anywhere in this module (a static scan in the unit suite pins
that: no chat-model import path exists here).

Persistence goes through the additive ``skill_rule_suggestions`` table (migration
``020``) and follows the house tenant discipline — **fail-closed**: an unresolved
tenant reads nothing and writes nothing (never a shared bucket).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Protocol, runtime_checkable

from forgeflow.config import get_settings
from forgeflow.repositories.base import new_id, utcnow
from forgeflow.skills.pattern_miner import (
    derive_run_outcome,
    run_id_of,
    step_status,
    step_tool,
)

logger = logging.getLogger(__name__)

